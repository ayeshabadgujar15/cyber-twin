'use strict';
const assert = require('node:assert/strict');
const model = require('./app/static/migration-model.js');
assert.equal(model.normalizeEmail('  OLD@Example.com '), 'old@example.com');
assert.throws(() => model.normalizeEmail('bad email'));
assert.equal(model.validDomain('https://example.com'), false);
assert.equal(model.validDomain('example.com'), true);
const plan = {email:'old@example.com', items:[]};
assert.equal(model.merge(plan, [{domain:'bank.example',service_name:'Bank'}, {domain:'bank.example'}, {domain:'bad/domain'}]), 1);
plan.items[0].priority = 'essential'; plan.items[0].status = 'updated';
assert.equal(model.merge(plan, [{domain:'bank.example'}, {domain:'shop.example'}]), 1);
assert.equal(plan.items[0].priority, 'essential');
assert.equal(plan.items[0].status, 'updated');
assert.equal(model.canImport(plan, {mailbox_email:'old@example.com'}, false, [{domain:'bank.example'}]), true);
assert.equal(model.canImport(plan, {mailbox_email:'other@example.com'}, false, [{domain:'bank.example'}]), false);
assert.equal(model.canImport(plan, {mailbox_email:'old@example.com'}, true, [{domain:'bank.example'}]), false);
assert.equal(model.canImport(plan, {mailbox_email:'old@example.com'}, false, [{provider:'github', domain:'github.com'}]), false);
assert.equal(model.canImport(plan, null, false, [{domain:'bank.example'}]), false);
assert.equal(plan.items[1].status, 'pending');
assert.deepEqual(model.read(JSON.stringify({version:1, plans:[plan]})), [plan]);
const another = {email:'other@example.com', items:[]};
model.merge(another, [{domain:'bank.example'}]);
assert.equal(another.items[0].status, 'pending');
assert.equal(plan.items[0].status, 'updated');
assert.throws(() => model.read('{broken'));
assert.throws(() => model.read(JSON.stringify({version:3, plans:[]})));
assert.throws(() => model.read(JSON.stringify({version:1, plans:[{email:'old@example.com', items:[{domain:'bank.example',name:'Bank',priority:'other',status:'bogus'}]}]})));
assert.throws(() => model.read(JSON.stringify({version:1, plans:[plan, plan]})));
console.log('Migration validation, deduplication, saved decisions and mailbox isolation checks passed.');
